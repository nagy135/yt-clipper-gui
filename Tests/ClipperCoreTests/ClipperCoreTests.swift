import Foundation
import Testing
@testable import ClipperCore

@Test func optionalTimesAndYouTubeURLs() throws {
    for link in ["https://www.youtube.com/watch?v=_g4l7YkDQwA", "https://youtu.be/_g4l7YkDQwA", "https://youtube.com/shorts/test"] {
        let request = try ClipRequest(link: link)
        #expect(request.start == 0)
        #expect(request.end == nil)
    }
    #expect(try ClipRequest.seconds("1:02:03.5") == 3723.5)
    #expect(try ClipRequest.seconds(" 0:18 ") == 18)
    #expect(try ClipRequest.seconds("90") == 90)
    #expect(try ClipRequest(link: "https://youtu.be/test", start: "18").end == nil)
    #expect(try ClipRequest(link: "https://youtu.be/test", end: "26").start == 0)
}

@Test func invalidInputs() {
    for time in ["-1", "NaN", "1:", ":2", "1:60", "1:2:3:4", "1.2:03", "1e10", "1; echo hi"] {
        #expect(throws: ClipError.self) { try ClipRequest.seconds(time) }
    }
    for link in ["file:///tmp/test", "https://youtube.com.evil.org/watch?v=x", "https://example.com", "https://user@youtube.com/test"] {
        #expect(throws: ClipError.self) { try ClipRequest(link: link) }
    }
    #expect(throws: ClipError.self) { try ClipRequest(link: "https://youtu.be/test", start: "26", end: "18") }
    #expect(throws: ClipError.self) { try ClipRequest(link: "https://youtu.be/test", start: "18", end: "18") }
}

/// Uses a local video and fake downloader, but real FFmpeg/ffprobe, without network access.
@Test func realVideoPipeline() async throws {
    let real = try Toolchain.discover()
    let fm = FileManager.default
    let directory = fm.temporaryDirectory.appendingPathComponent("clipper-test-\(UUID())")
    try fm.createDirectory(at: directory, withIntermediateDirectories: true)
    defer { try? fm.removeItem(at: directory) }
    let fixture = directory.appendingPathComponent("fixture.mp4")
    let setup = CommandRunner()
    _ = try await setup.run(real.ffmpeg, ["-v", "error", "-f", "lavfi", "-i", "testsrc2=size=160x90:rate=10", "-f", "lavfi", "-i", "sine=frequency=440", "-t", "3", "-c:v", "libx264", "-c:a", "aac", fixture.path], path: real.path)
    let fake = directory.appendingPathComponent("yt-dlp")
    // Paths generated by this test contain no single quotes.
    try """
    #!/bin/bash
    set -eu
    while (( $# )); do
      case "$1" in
        --print-to-file) manifest="$3"; shift 3 ;;
        *) shift ;;
      esac
    done
    printf '%s\\n' '\(fixture.path)' > "$manifest"
    """.write(to: fake, atomically: true, encoding: .utf8)
    try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: fake.path)
    let tools = Toolchain(ytDLP: fake, ffmpeg: real.ffmpeg, ffprobe: real.ffprobe, path: real.path)
    for (start, end, expected) in [("", "", 3.0), ("1", "", 2.0), ("", "2", 2.0), ("1", "2", 1.0)] {
        let request = try ClipRequest(link: "https://youtu.be/test", start: start, end: end)
        let file = try await ClipEngine().create(request, tools: tools, runner: CommandRunner(), outputDirectory: directory) { _ in }
        let duration = try await setup.run(real.ffprobe, ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file.path], path: real.path)
        #expect(abs(Double(duration.trimmingCharacters(in: .whitespacesAndNewlines))! - expected) < 0.2)
        #expect(file.pathExtension == "mp4")
    }
    await #expect(throws: ClipError.self) {
        _ = try await ClipEngine().create(ClipRequest(link: "https://youtu.be/test", end: "10"), tools: tools, runner: CommandRunner(), outputDirectory: directory) { _ in }
    }
}

@Test func commandFailureAndCancellation() async throws {
    let runner = CommandRunner()
    await #expect(throws: ClipError.self) {
        _ = try await runner.run(URL(fileURLWithPath: "/bin/sh"), ["-c", "echo failure >&2; exit 3"], path: "/usr/bin:/bin")
    }
    let running = Task { try await runner.run(URL(fileURLWithPath: "/bin/sleep"), ["30"], path: "/usr/bin:/bin") }
    try await Task.sleep(for: .milliseconds(100))
    await runner.cancel()
    await #expect(throws: CancellationError.self) { try await running.value }
}

@Test(.enabled(if: ProcessInfo.processInfo.environment["YT_CLIPPER_LIVE_TEST"] == "1"))
func liveYouTubeDownload() async throws {
    let tools = try Toolchain.discover()
    let output = FileManager.default.temporaryDirectory.appendingPathComponent("clipper-live-\(UUID())")
    defer { try? FileManager.default.removeItem(at: output) }
    let file = try await ClipEngine().create(
        ClipRequest(link: "https://www.youtube.com/watch?v=jNQXAC9IVRw", start: "1", end: "3"),
        tools: tools, runner: CommandRunner(), outputDirectory: output) { print($0) }
    let duration = try await CommandRunner().run(tools.ffprobe, ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file.path], path: tools.path)
    #expect(abs(Double(duration.trimmingCharacters(in: .whitespacesAndNewlines))! - 2) < 0.2)
}
